import React from 'react';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import NSEElogUpload from './NSEElogUpload';
import { NSE_TOKEN_KEY } from '@/services/nseApi';
afterEach(() => { cleanup(); vi.unstubAllGlobals(); sessionStorage.clear(); });
it('uses date/time pickers and submits the chosen timestamp only after confirmation', async () => {
 sessionStorage.setItem(NSE_TOKEN_KEY, 'test-token');
 const fetcher = vi.fn(async (_url: string, options: RequestInit) => ({ ok: true, status: 200, text: async () => JSON.stringify({ ...JSON.parse(String(options.body)), elog_status: '100', elog_status_message: 'Uploaded' }) }));
 vi.stubGlobal('fetch', fetcher);
 render(<NSEElogUpload />);
 fireEvent.click(screen.getByText('Upload holder eLOG'));
 fireEvent.change(screen.getByLabelText('eLOG client code'), { target: { value: 'TEST001' } });
 fireEvent.change(screen.getByLabelText('Holder 1 PAN'), { target: { value: 'ABCPD1234F' } });
 fireEvent.change(screen.getByLabelText('Holder 1 Consent IP address'), { target: { value: '203.0.113.10' } });
 expect(screen.getByLabelText('Holder 1 Recorded consent date')).toHaveAttribute('type', 'date');
 expect(screen.getByLabelText('Holder 1 Recorded consent time')).toHaveAttribute('type', 'time');
 fireEvent.change(screen.getByLabelText('Holder 1 Recorded consent date'), { target: { value: '2026-10-21' } });
 fireEvent.change(screen.getByLabelText('Holder 1 Recorded consent time'), { target: { value: '13:45:12' } });
 expect(screen.getByText('Mutual funds log time: 21-OCT-26 13:45:12')).toBeInTheDocument();
 fireEvent.click(screen.getByRole('button', { name: 'Review eLOG upload' }));
 expect(fetcher).not.toHaveBeenCalled();
 expect(screen.getByRole('button', { name: 'Confirm eLOG upload' })).toBeDisabled();
 fireEvent.click(screen.getByRole('checkbox'));
 fireEvent.click(screen.getByRole('button', { name: 'Confirm eLOG upload' }));
 await screen.findByText(/Uploaded Check the eLOG report/);
 expect(JSON.parse(String(fetcher.mock.calls[0][1].body))).toMatchObject({ primary_holder_ip_address: '203.0.113.10', primary_holder_log_date: '21-OCT-26 13:45:12' });
});
it('offers only previously entered valid IPs and leaves each new holder blank', () => {
 render(<NSEElogUpload />); fireEvent.click(screen.getByText('Upload holder eLOG'));
 const ip = screen.getByLabelText('Holder 1 Consent IP address');
 expect(ip).toHaveValue('');
 const list = document.getElementById(ip.getAttribute('list')!)!;
 expect(list.querySelectorAll('option')).toHaveLength(0);
 fireEvent.change(ip, { target: { value: '999.1.1.1' } }); fireEvent.blur(ip);
 expect(list.querySelectorAll('option')).toHaveLength(0);
 fireEvent.change(ip, { target: { value: '203.0.113.10' } }); fireEvent.blur(ip);
 expect(list.querySelector('option')).toHaveValue('203.0.113.10');
 fireEvent.change(screen.getByLabelText('Number of UCC holders'), { target: { value: '2' } });
 expect(screen.getByLabelText('Holder 2 Consent IP address')).toHaveValue('');
 expect(screen.getByLabelText('Holder 2 Consent IP address')).toHaveAttribute('list', ip.getAttribute('list'));
 expect(screen.getByLabelText('Holder 2 Recorded consent date')).toHaveValue('');
 expect(screen.getByLabelText('Holder 2 Recorded consent time')).toHaveValue('');
});
