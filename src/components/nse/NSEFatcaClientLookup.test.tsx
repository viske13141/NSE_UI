import React from 'react';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import NSEFatcaRegistration from './NSEFatcaRegistration';
import { NSE_TOKEN_KEY } from '@/services/nseApi';
afterEach(() => { cleanup(); vi.unstubAllGlobals(); sessionStorage.clear(); });
const master = { response_status: 'S', report_data_total: '1', report_data: [{ client_code: 'TEST01', primary_holder_first_name: 'First Investor', primary_holder_pan: 'ABCPD1234F', tax_status: '01', primary_holder_dob_incorporation: '15/06/1990', second_holder_first_name: 'Joint Investor', second_holder_pan: 'ABCPD2345F' }] };
function mock(reports: unknown[]) {
 sessionStorage.setItem(NSE_TOKEN_KEY, 'test-token');
 const fetcher = vi.fn().mockResolvedValueOnce({ ok: true, status: 200, text: async () => JSON.stringify(master) });
 reports.forEach(body => fetcher.mockResolvedValueOnce({ ok: true, status: 200, text: async () => JSON.stringify(body) }));
 vi.stubGlobal('fetch', fetcher); return fetcher;
}
it('prefills a holder, highlights missing fields, resets on holder switch, and makes only read requests', async () => {
 const fetcher = mock([{ response_status: 'S', report_data: [{ pan_rp: 'ABCPD1234F', tax_res1: 'IN', co_bir_inc: 'IN', tpin1: 'FIRST-TIN', id1_type: 'C' }] }, { response_status: 'S', report_data: [] }]);
 render(<NSEFatcaRegistration onClose={vi.fn()} />);
 fireEvent.change(screen.getByLabelText('Client code / name'), { target: { value: 'TEST01' } });
 fireEvent.click(screen.getByRole('button', { name: 'Search clients' }));
 await screen.findByRole('option', { name: 'TEST01 - First Investor' });
 fireEvent.change(screen.getByLabelText('Client'), { target: { value: '0' } });
 fireEvent.change(screen.getByLabelText('Holder / PAN'), { target: { value: 'primary_holder' } });
 await screen.findByText(/Client Master and the existing FATCA declaration have been loaded/);
 let form = screen.getByRole('heading', { name: 'Submit individual FATCA data' }).parentElement!;
 expect(within(form).getByLabelText('Investor / guardian name')).toHaveValue('First Investor');
 expect(within(form).getByLabelText('Taxpayer identification number')).toHaveValue('FIRST-TIN');
 expect(within(form).getByLabelText('Place of birth')).toHaveClass('border-amber-500');
 expect(screen.getByRole('button', { name: 'Check FATCA processing report' })).toBeInTheDocument();
 fireEvent.change(screen.getByLabelText('Holder / PAN'), { target: { value: 'second_holder' } });
 await screen.findByText(/No FATCA record was returned/);
 form = screen.getByRole('heading', { name: 'Submit individual FATCA data' }).parentElement!;
 expect(within(form).getByLabelText('Investor / guardian name')).toHaveValue('Joint Investor');
 expect(within(form).getByLabelText('Taxpayer identification number')).toHaveValue('');
 expect(within(form).getByLabelText('Tax status')).toHaveValue('');
 expect(fetcher.mock.calls.map(call => call[0])).toEqual(['/nse-api/reports/client-master', '/nse-api/reports/fatca', '/nse-api/reports/fatca']);
 expect(JSON.parse(fetcher.mock.calls[2][1].body).pan_pkern_no).toBe('ABCPD2345F');
}, 15000);
it('requires a choice when multiple saved declarations exist', async () => {
 mock([{ response_status: 'S', report_data: [{ pan_rp: 'ABCPD1234F', tpin1: 'ONE' }, { pan_rp: 'ABCPD1234F', tpin1: 'TWO' }] }]);
 render(<NSEFatcaRegistration onClose={vi.fn()} />);
 fireEvent.change(screen.getByLabelText('Client code / name'), { target: { value: 'TEST01' } });
 fireEvent.click(screen.getByRole('button', { name: 'Search clients' }));
 await screen.findByRole('option', { name: 'TEST01 - First Investor' });
 fireEvent.change(screen.getByLabelText('Client'), { target: { value: '0' } });
 fireEvent.change(screen.getByLabelText('Holder / PAN'), { target: { value: 'primary_holder' } });
 await screen.findByText(/More than one FATCA record/);
 expect(screen.getByLabelText('Saved FATCA declaration')).toHaveValue('');
 fireEvent.change(screen.getByLabelText('Saved FATCA declaration'), { target: { value: '1' } });
 const form = screen.getByRole('heading', { name: 'Submit individual FATCA data' }).parentElement!;
 expect(within(form).getByLabelText('Taxpayer identification number')).toHaveValue('TWO');
 await waitFor(() => expect(screen.getByRole('button', { name: 'Search clients' })).toBeEnabled());
}, 15000);

it('requires review and consent after prefill, submits once, and opens the selected holder report', async () => {
 const saved = { pan_rp: 'ABCPD1234F', inv_name: 'First Investor', tax_status: '01', po_bir_inc: 'City', co_bir_inc: 'IN', tax_res1: 'IN', tpin1: 'ABCPD1234F', id1_type: 'C', srce_wealt: '01', inc_slab: '31', occ_code: '44', occ_type: 'S', ubo_code: 'C14', data_src: 'P', addr_type: '2', pep_flag: 'N', npo_form: 'N', reg_id: '100', reg_status: 'REG_SUCCESS' };
 const fetcher = mock([{ response_status: 'S', report_data: [saved] }, { reg_details: [{ pan_rp: 'ABCPD1234F', reg_status: 'REG_SUCCESS', reg_id: '456' }] }, { response_status: 'S', report_data: [{ pan_rp: 'ABCPD1234F', inv_name: 'First Investor', camsuploadstatus: 'UPLOADED', camsresponsestatus: 'PENDING' }] }]);
 render(<NSEFatcaRegistration onClose={vi.fn()} />);
 fireEvent.change(screen.getByLabelText('Client code / name'), { target: { value: 'TEST01' } });
 fireEvent.click(screen.getByRole('button', { name: 'Search clients' }));
 await screen.findByRole('option', { name: 'TEST01 - First Investor' });
 fireEvent.change(screen.getByLabelText('Client'), { target: { value: '0' } });
 fireEvent.change(screen.getByLabelText('Holder / PAN'), { target: { value: 'primary_holder' } });
 await screen.findByText(/Client Master and the existing FATCA declaration have been loaded/);
 fireEvent.click(screen.getByRole('button', { name: 'Review FATCA submission' }));
 expect(fetcher).toHaveBeenCalledTimes(2);
 const confirm = screen.getByRole('button', { name: 'Confirm FATCA submission' });
 expect(confirm).toBeDisabled();
 fireEvent.click(screen.getByRole('checkbox'));
 fireEvent.click(confirm);
 await screen.findByText(/Registration ID: 456/);
 expect(fetcher).toHaveBeenCalledTimes(3);
 expect(fetcher.mock.calls[2][0]).toBe('/nse-api/fatca/upload');
 const submitted = JSON.parse(fetcher.mock.calls[2][1].body).reg_details[0];
 expect(submitted).toMatchObject({ pan_rp: saved.pan_rp, occ_code: '44', occ_type: 'S' });
 expect(submitted).not.toHaveProperty('reg_id');
 await waitFor(() => expect(screen.getByRole('button', { name: 'Check FATCA processing report' })).toBeEnabled());
 fireEvent.click(screen.getByRole('button', { name: 'Check FATCA processing report' }));
 expect(await screen.findByRole('heading', { name: 'FATCA submission report' })).toBeInTheDocument();
 expect(screen.getByLabelText('PAN / PKERN identifiers')).toHaveValue('ABCPD1234F');
 fireEvent.click(screen.getByRole('button', { name: 'Load FATCA report' }));
 await screen.findByText('Upload: UPLOADED');
 expect(fetcher.mock.calls[3][0]).toBe('/nse-api/reports/fatca');
}, 15000);
