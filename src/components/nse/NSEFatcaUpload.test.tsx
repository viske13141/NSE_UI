import React from 'react';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import NSEFatcaUpload from './NSEFatcaUpload';
import { NSE_TOKEN_KEY } from '@/services/nseApi';
afterEach(() => { cleanup(); vi.unstubAllGlobals(); sessionStorage.clear(); });
it('allows correcting local validation failures and does not ask to check a report before a request', async () => {
  sessionStorage.setItem(NSE_TOKEN_KEY, 'test-token');
  const fetcher = vi.fn().mockResolvedValue({ ok: true, status: 200, text: async () => JSON.stringify({ status: '100', message: 'Image uploaded' }) });
  vi.stubGlobal('fetch', fetcher);
  const selectIndividual = vi.fn();
  render(<NSEFatcaUpload embedded initialPan="ABCPD1234F" onSelectIndividual={selectIndividual} />);
  fireEvent.click(screen.getByRole('button', { name: 'Use Individual declaration for this PAN' }));
  expect(selectIndividual).toHaveBeenCalledTimes(1);
  fireEvent.change(screen.getByLabelText('Signed FATCA image'), { target: { files: [new File([new Uint8Array([255, 216, 255, 224, 0])], 'signed.jpg')] } });
  fireEvent.click(screen.getByRole('checkbox'));
  fireEvent.click(screen.getByRole('button', { name: 'Upload FATCA to Mutual funds' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('choose Individual declaration');
  expect(screen.getByRole('alert')).not.toHaveTextContent('Check the FATCA report');
  expect(fetcher).not.toHaveBeenCalled();
  expect(screen.getByLabelText('Non-individual / HUF PAN')).toBeEnabled();
  fireEvent.change(screen.getByLabelText('Non-individual / HUF PAN'), { target: { value: 'ABCHD1234F' } });
  fireEvent.click(screen.getByRole('checkbox'));
  fireEvent.click(screen.getByRole('button', { name: 'Upload FATCA to Mutual funds' }));
  await screen.findByText(/Image uploaded/);
  expect(fetcher).toHaveBeenCalledTimes(1);
});
