import React from 'react';
import { afterEach, expect, it } from 'vitest';
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react';
import NSEUccRegistration from './NSEUccRegistration';
afterEach(cleanup);
it('offers the documented client master choices and retains their exact codes', () => {
  render(<NSEUccRegistration onClose={() => {}} />);
  const occupation = screen.getByRole('combobox', { name: 'Occupation' });
  expect(within(occupation).getAllByRole('option')).toHaveLength(9);
  expect(within(occupation).getByRole('option', { name: 'Business' })).toHaveValue('01');
  expect(within(occupation).getByRole('option', { name: 'Student' })).toHaveValue('07');
  fireEvent.change(occupation, { target: { value: '03' } });
  expect(occupation).toHaveValue('03');
  expect(screen.getByRole('combobox', { name: 'Investor type' })).toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: '3. Contact and address' }));
  expect(within(screen.getByLabelText('State')).getByRole('option', { name: 'Bihar' })).toHaveValue('BH');
  expect(within(screen.getByLabelText('Country')).getByRole('option', { name: 'India' })).toHaveValue('101');
  fireEvent.click(screen.getByRole('button', { name: '4. KYC and declarations' }));
  expect(within(screen.getByLabelText('Mobile number belongs to')).getByRole('option', { name: 'Self' })).toHaveValue('SE');
  fireEvent.click(screen.getByRole('button', { name: '5. Nomination' }));
  fireEvent.change(screen.getByLabelText('Nomination choice'), { target: { value: 'Y' } });
  expect(within(screen.getByLabelText('Relationship to investor')).getByRole('option', { name: 'Spouse' })).toHaveValue('20');
  expect(screen.queryByText(/options pending/)).not.toBeInTheDocument();
});
