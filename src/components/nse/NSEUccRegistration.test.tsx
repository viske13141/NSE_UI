it('adds up to three nominees, retains their details and removes the selected nominee', () => {
  render(<NSEUccRegistration onClose={() => {}} />);
  fireEvent.click(screen.getByRole('button', { name: '5. Nomination' }));
  fireEvent.change(screen.getByLabelText('Nomination choice'), { target: { value: 'Y' } });
  fireEvent.change(screen.getByLabelText('Nominee name'), { target: { value: 'First' } });
  expect(screen.getByLabelText('Share (%)')).toHaveValue(100);
  fireEvent.click(screen.getByRole('button', { name: '+ Add another nominee' }));
  fireEvent.change(screen.getByLabelText('Nominee 2: Nominee name'), { target: { value: 'Second' } });
  expect(screen.getByLabelText('Nominee 2: Nominee identity type').tagName).toBe('SELECT');
  expect(screen.getByLabelText('Nominee 2: Nominee address line 2 (optional)')).toHaveAttribute('aria-required', 'false');
  fireEvent.change(screen.getByLabelText('Share (%)'), { target: { value: '60' } });
  fireEvent.change(screen.getByLabelText('Nominee 2: Share (%)'), { target: { value: '40' } });
  expect(screen.getByText('Total share: 100% / 100%')).toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: '+ Add another nominee' }));
  fireEvent.change(screen.getByLabelText('Nominee 3: Nominee name'), { target: { value: 'Third' } });
  expect(screen.queryByRole('button', { name: '+ Add another nominee' })).not.toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: 'Remove nominee 2' }));
  expect(screen.getByLabelText('Nominee name')).toHaveValue('First');
  expect(screen.getByLabelText('Nominee 2: Nominee name')).toHaveValue('Third');
  fireEvent.click(screen.getByRole('button', { name: 'Remove nominee 1' }));
  expect(screen.getByLabelText('Nominee name')).toHaveValue('Third');
  expect(screen.getByLabelText('Share (%)')).toHaveValue(100);
  expect(screen.queryByLabelText('Nominee 2: Nominee name')).not.toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: '+ Add another nominee' }));
  expect(screen.getByLabelText('Nominee 2: Nominee name')).toHaveValue('');
  fireEvent.change(screen.getByLabelText('Nomination choice'), { target: { value: 'N' } });
  fireEvent.change(screen.getByLabelText('Nomination choice'), { target: { value: 'Y' } });
  expect(screen.getByLabelText('Nominee name')).toHaveValue('');
  expect(screen.queryByLabelText('Nominee 2: Nominee name')).not.toBeInTheDocument();
});
